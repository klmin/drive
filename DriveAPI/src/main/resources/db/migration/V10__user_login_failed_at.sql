-- -------------------------------------------------------------------------------------
-- 로그인 실패 잠금을 시간으로 풀리게 한다(docs/design/scaling-strategy.md §3-5).
--   지금까지는 5회 실패로 잠기면 비밀번호를 바꿀 때만 풀려, 아이디만 알면 5번 틀려 계정을 계속 잠가 둘 수 있었다.
--   마지막 실패 시각을 두고, 그 뒤 15분이 지나면 다음 시도에서 횟수를 1부터 다시 센다(스케줄러 없음).
-- 배포 시점에 이미 실패 횟수가 있는 계정은 지금 시각을 넣는다 — 잠긴 계정은 배포 후 15분 동안 그대로 잠겨 있다.
--   (NULL 이면 "오래전 실패" 로 보아 다음 시도에서 바로 1부터 센다.)
-- 컬럼 추가(NULL 허용, 기본값 없음)라 테이블 재작성 없음. UPDATE 는 실패 횟수가 있는 계정만.
-- -------------------------------------------------------------------------------------

ALTER TABLE tb_user ADD COLUMN login_failed_at timestamptz DEFAULT NULL;

COMMENT ON COLUMN tb_user.login_failed_at IS '마지막 로그인 실패(시도) 시각 — 이 시각 + 15분이 지나면 실패 횟수를 1부터 다시 센다. NULL 이면 오래전으로 본다';

UPDATE tb_user SET login_failed_at = CURRENT_TIMESTAMP WHERE login_failure_count > 0;
