-- -------------------------------------------------------------------------------------
-- tb_storage_deletion — 스토리지 객체 삭제 대기열(아웃박스)
--   DB 행을 지우는 트랜잭션 안에서 삭제할 스토리지 키를 함께 넣고(커밋되면 둘 다, 롤백되면 둘 다 없음),
--   스케줄러(SchedulerService#processStorageDeletions)가 꺼내 스토리지에서 지운 뒤 행을 지운다.
--   실패하면 attempt_count 를 올리고 next_attempt_date 를 뒤로 미룬다. 최대 횟수에 닿은 행은 남겨 둔다(수동 확인).
--   시각(next_attempt_date·register_date)은 앱이 넣는다(DB 기본값 없음 — 빠뜨리면 NOT NULL 로 실패).
--   테넌트·사용자와 무관한 테이블(키에 user_seq 가 들어 있음) — 파티션·FK·유니크 없음(같은 키 중복은 삭제가 멱등이라 무해).
-- -------------------------------------------------------------------------------------

CREATE TABLE tb_storage_deletion (
  storage_deletion_seq bigint        GENERATED BY DEFAULT AS IDENTITY,
  storage_key          varchar(1024) NOT NULL,
  attempt_count        integer       NOT NULL DEFAULT 0,
  next_attempt_date    timestamptz   NOT NULL,
  last_error           varchar(1000) DEFAULT NULL,
  register_date        timestamptz   NOT NULL,
  PRIMARY KEY (storage_deletion_seq)
);
CREATE INDEX idx_storage_deletion_next_attempt ON tb_storage_deletion (next_attempt_date, storage_deletion_seq);
COMMENT ON TABLE  tb_storage_deletion                      IS '스토리지 객체 삭제 대기열';
COMMENT ON COLUMN tb_storage_deletion.storage_deletion_seq IS '삭제 대기 seq';
COMMENT ON COLUMN tb_storage_deletion.storage_key          IS '삭제할 스토리지 키';
COMMENT ON COLUMN tb_storage_deletion.attempt_count        IS '실패한 시도 횟수';
COMMENT ON COLUMN tb_storage_deletion.next_attempt_date    IS '다음 시도 가능 시각';
COMMENT ON COLUMN tb_storage_deletion.last_error           IS '마지막 실패 사유';
COMMENT ON COLUMN tb_storage_deletion.register_date        IS '등록시간';
