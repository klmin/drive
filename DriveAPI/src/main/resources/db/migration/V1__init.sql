-- =====================================================================================
-- Thinkfree Drive - Flyway V1 : PostgreSQL 18 초기 스키마 + 기초 데이터
-- 구 DriveInstaller/thinkfree/TFD/template/database/postgres/init/initialize.sql 을 옮긴 것.
--   차이: BEGIN/COMMIT 제거(트랜잭션은 Flyway 가 잡는다), tb_system_config 의 office 빈 행 2개(office_domain·office_adapter_name) 제거,
--         tb_license.name 컬럼 제거(코드가 읽지도 쓰지 않던 컬럼 — 예전 DB 에 남아 있어도 동작 영향 없음).
--   예전 initialize.sql 로 만든 DB 에 남은 그 빈 행은 동작에 영향이 없다(빈 주소 = office 미사용, office_adapter_name 은 코드가 읽지 않는 옛 키).
--
-- ⚠️ 이미 적용된 마이그레이션이다 — 이 파일은 고치지 않는다(checksum 이 바뀌면 validate 에서 기동 실패).
--    스키마·기초 데이터 변경은 새 V 파일(V2__..., V3__...)로 추가한다.
--
-- 실행 전제
--   1) DB·계정은 Flyway 밖(도커 initdb·설치기·DBA)에서 먼저 만든다
--        CREATE ROLE t_drive_user LOGIN PASSWORD '<password>';
--        CREATE DATABASE t_drive OWNER t_drive_user ENCODING 'UTF8';
--   2) 앱 기동 시 Flyway 가 t_drive_user 로 이 파일을 실행한다(빈 DB 일 때만).
--      이미 initialize.sql 로 만든 DB 는 baseline(V1 적용됨 기록)만 하고 이 파일은 실행하지 않는다.
--   3) 본문의 ${...} 는 Flyway placeholder 가 아니다(spring.flyway.placeholder-replacement=false).
--   4) 이메일 템플릿의 시각 리터럴('2025-07-18 17:34:25')은 접속 세션 timezone(JVM 기본 시간대) 기준으로 해석된다.
--
-- MySQL → PostgreSQL 변환 규칙
--   datetime / timestamp            → timestamptz (세션 timezone = Asia/Seoul 전제)
--   AUTO_INCREMENT                  → GENERATED BY DEFAULT AS IDENTITY (명시 값 INSERT 허용)
--   json                            → jsonb
--   blob / mediumblob / longblob    → bytea (Spring Authorization Server oauth2_* 는 공식 PG 스크립트대로 text)
--   int unsigned / tinyint unsigned → integer, bigint / smallint
--   char(1) 'Y'/'N' 플래그          → 유지 (BooleanTypeHandler 호환)
--   ON UPDATE CURRENT_TIMESTAMP     → 제거 (UserAuditInterceptor 가 update_date 를 세팅)
--   PARTITION BY HASH               → PARTITION BY HASH (user_seq) + 파티션 2개(<table>_p0/_p1, MODULUS 2) 로 동일 유지 (09-29 사용자 결정)
--     · 대상 11테이블: tb_notification, tb_pinned_folder, tb_recent, tb_resource, tb_resource_tag, tb_resource_version,
--                     tb_share, tb_share_target, tb_starred, tb_trash, tb_user_quota_alert_state
--     · MySQL 의 (user_seq % 2) 표현식 키는 PG 에서는 user_seq 컬럼 키로 — PG 플래너는 WHERE user_seq = ? 로만 파티션 프루닝하므로
--     · PK/UNIQUE 는 모두 user_seq 를 포함해야 함(PG 파티션 제약) — MySQL 과 동일하게 이미 포함
--     · IDENTITY 는 부모(파티션 테이블)에만 두고 파티션이 시퀀스를 공유(PG 17+)
--   함수 기반 UNIQUE KEY            → 표현식 / 부분(partial) UNIQUE INDEX
--   GENERATED ... VIRTUAL           → GENERATED ... STORED (인덱스 대상이라 STORED 필수)
--   COMMENT '...'                   → COMMENT ON TABLE / COLUMN
--   MySQL 은 인덱스명이 테이블별, PG 는 스키마 전체에서 유일 → 중복되던 인덱스명은 테이블 접두로 개명
--     (uniq_tenant, idx_user_seq, idx_expiration_date, idx_register_date, token_hash, tenant_name,
--      idx_notification_event_sort(tb_notification_event 쪽), fk_user_log_user_seq(인덱스))
--
-- 콜레이션 (09-29 결정)
--   값 비교는 PG 기본(대소문자 구분) 유지 — 드라이브 서비스 특성상 a.txt 와 A.txt 는 다른 파일.
--   이름 정렬만 ICU 콜레이션 drive_name_sort(deterministic) 로 글자 순 섞기(소문자 먼저) — 매퍼 SQL·정렬 인덱스에서 지정. 정의는 BEGIN 직후.
--   로그인 user_id 도 구분 → 대문자 섞인 기존 아이디는 앱에서 소문자 정규화 여부 별도 결정.
-- =====================================================================================


-- -------------------------------------------------------------------------------------
-- 콜레이션 (사용자 결정 09-29: 대소문자 구분 유지, 정렬만 ICU 언어 규칙)
--   deterministic = true 라 = 비교·UNIQUE 는 대소문자 구분(PG 기본과 동일), ORDER BY 만
--   a A a (1) apple Apple b B … 처럼 글자 순으로 섞이고 같은 글자면 소문자가 먼저 온다(C.UTF-8 은 A B a b 순).
--   컬럼에는 붙이지 않고(테이블 정의·컬럼 순서 유지) 매퍼 SQL 의 ORDER BY·커서 튜플과 idx_resource_sort_resource_name 인덱스 식에서
--   `COLLATE drive_name_sort` 로 지정한다. 등호 비교(중복 검사 등)는 컬럼 기본 콜레이션(대소문자 구분) 그대로. ICU 버전 업 시 ALTER COLLATION drive_name_sort REFRESH VERSION + REINDEX.
-- -------------------------------------------------------------------------------------
CREATE COLLATION drive_name_sort (provider = icu, locale = 'und', deterministic = true);

